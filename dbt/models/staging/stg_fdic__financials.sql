-- One row per bank per quarter, as reported. Amounts in $ thousands (suffix _k);
-- income items (net_income_ytd_k, provision_for_losses_ytd_k) are year-to-date.
select
    cast(cert as integer)                 as cert,
    report_date,
    total_assets_k,
    total_deposits_k,
    domestic_deposits_k,
    brokered_deposits_k,
    net_loans_k,
    gross_loans_k,
    total_equity_k,
    other_real_estate_owned_k,
    net_income_ytd_k,
    provision_for_losses_ytd_k,
    roa_pct,
    roe_pct,
    net_interest_margin_pct,
    efficiency_ratio_pct,
    noncurrent_loans_pct,
    net_chargeoff_rate_pct,
    past_due_30_89_k,
    past_due_90_plus_k,
    nonaccrual_assets_k,
    tier1_leverage_pct,
    total_risk_based_capital_pct,
    real_estate_loans_k,
    construction_loans_k,
    multifamily_loans_k,
    nonfarm_nonres_loans_k,
    residential_re_loans_k,
    commercial_industrial_loans_k,
    consumer_loans_k,
    agricultural_loans_k,
    -- reporting flags: CBLR bank (from 2020; NULL before), International Banking Act entity
    cast(cblr_indicator as integer)       as cblr_indicator,
    cast(iba_flag as integer)             as iba_flag,
    _loaded_at
from {{ source('raw', 'fdic_financials') }}
